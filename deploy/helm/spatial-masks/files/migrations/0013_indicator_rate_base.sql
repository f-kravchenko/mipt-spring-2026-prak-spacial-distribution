-- 0013_indicator_rate_base.sql
-- Удельные показатели (ставки) больше не разносятся как объёмы.
--
-- Проблема. Инвариант платформы — Σ по ячейкам = региональное значение
-- (distribute_value: value_i = rv · w_i / Σw). Для КОЭФФИЦИЕНТА это неверно по
-- смыслу при любом знаке: сумма коэффициентов рождаемости по ячейкам не равна
-- коэффициенту по региону, а ячейке достаётся величина, которая не является ни
-- ставкой, ни числом людей. У Y477110196 (естественный прирост) значение
-- отрицательно в трёх пилотных регионах из четырёх (МО −2,5, Краснодар −3,2,
-- НСО −3,5), и там же ошибка становилась видимой:
--   * Джини сохранялся отрицательным (−0,515 при 0,515 у объёмного показателя
--     с тем же рельефом) — вне области определения метрики;
--   * порог пиков peak_threshold = p95 · rv/total тоже отрицателен, а фронт
--     фильтрует value >= peak_threshold: при rv < 0 неравенство переворачивается
--     и «пиком» становились 95 % ячеек (134 868 из 141 967 в МО);
--   * шкала цвета на отрицательном value_max откатывалась на vmax = 1 и красила
--     регион одним нижним цветом.
--
-- Правильный инвариант для ставки — взвешенное СРЕДНЕЕ, а не сумма:
--   rate_i = rv · w_i / w̄,  w̄ = Σ(base_j·w_j)/Σbase_j
--   =>  Σ(base_i·rate_i)/Σbase_i = rv
-- base — знаменатель самой ставки: население (на 1000/10000 чел., кв.м на
-- жителя) или площадь (км дорог на 1000 кв.км).
--
-- rate_base = NULL — объёмный показатель, поведение прежнее (Σ = rv).
ALTER TABLE indicator ADD COLUMN IF NOT EXISTS rate_base text;

-- Миграции прогоняются целиком на каждом деплое, поэтому ограничение
-- пересоздаётся, а не добавляется (иначе второй прогон падает).
ALTER TABLE indicator DROP CONSTRAINT IF EXISTS indicator_rate_base_chk;
ALTER TABLE indicator ADD CONSTRAINT indicator_rate_base_chk
    CHECK (rate_base IS NULL OR rate_base IN ('population', 'area'));

-- Разметка уже загруженных показателей: живой путь (recompute + tile_composition)
-- считает всё от mask_cell_value и composition.regional_value, поэтому карта и
-- пики становятся корректными сразу после миграции, не дожидаясь прогона ETL.
-- Самоотключаемо: трогаем только строки, где признак ещё не задан.
UPDATE indicator SET rate_base = 'population' WHERE rate_base IS NULL AND code IN (
    'Y477110231',  -- общие коэффициенты рождаемости, на 1000 чел.
    'Y477110196',  -- коэффициенты естественного прироста, на 1000 чел.
    'Y477110197',  -- коэффициенты миграционного прироста, на 10000 чел.
    'Y477110226',  -- общая площадь жилых помещений, кв.м на жителя
    'Y477110211',  -- мощность поликлиник, посещений в смену на 10000 чел.
    'Y477110217'   -- места в дошкольных организациях, на 1000 детей: истинный
                   -- знаменатель — дети, приближаем населением (сетки детей нет)
);
UPDATE indicator SET rate_base = 'area' WHERE rate_base IS NULL AND code IN (
    'Y477110295'   -- плотность автодорог, км на 1000 кв.км — знаменатель площадь
);

-- Единицы этих коэффициентов в БД были 'ND' — это сентинел indicator_unit из
-- parquet Росстата, а не подпись; интерфейс так и показывал «[ND]».
UPDATE indicator SET unit = 'на 1000 чел.'  WHERE unit = 'ND' AND code IN ('Y477110231', 'Y477110196');
UPDATE indicator SET unit = 'на 10000 чел.' WHERE unit = 'ND' AND code = 'Y477110197';

-- Сохранённые метрики ablation для ставок считались по знаковым значениям:
-- Джини выходил из [0,1] (знак переворачивался), top10_share брал наименее
-- концентрированные ячейки (0,003 вместо 0,326 — сменой знака не восстановить),
-- а sum_error проверял неверный инвариант. Ни одну из трёх нельзя починить на
-- месте, поэтому удаляем все — их пересчитает следующий прогон etl.ingest
-- (по рельефу масок для Джини/top10 и mean_error для инварианта).
--
-- ВАЖНО: etl.enabled=false по умолчанию (values.yaml), CI его не включает —
-- деплой накатывает только миграции. То есть после деплоя метрики ablation у
-- удельных показателей будут ПУСТЫ до ручного прогона etl.ingest. Это офлайн-
-- артефакт §9.5: живой путь (карта, пики, шкала) считает всё от
-- mask_cell_value и composition.regional_value и корректен сразу.
-- Самоотключаемо: на повторном прогоне удалять уже нечего.
DELETE FROM quality_metric q
USING composition c, indicator i
WHERE q.composition_id = c.id
  AND i.code = c.indicator_code
  AND i.rate_base IS NOT NULL
  AND q.metric IN ('gini', 'top10_share', 'sum_error');
