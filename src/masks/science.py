"""
Маска близости к научно-образовательной инфраструктуре.

Зачем. Показатели научно-технологического блока (патенты, персонал НИОКР,
научные организации, разработанные технологии) до этой маски опирались на
distance_to_center + worldpop, то есть на «где вообще живут люди» и «где центр
региона». Это плохой прокси: наука сидит не в геометрическом центре и не
пропорционально населению, а в конкретных точках — вузовских кампусах,
академгородках, НИИ. Маска даёт им собственный пространственный сигнал.

Она же закрывает пункты ТЗ про лаборатории/ПИШ/ЦКП и «наличие ЦКПНО и иных
организаций»: реестры Минобрнауки перечисляют организации, а ЦКП и ПИШ физически
стоят в тех же кампусах и НИИ, которые OSM отдаёт с координатами. Реестр даёт
названия, OSM — точки; для маски по сетке 1 км нужны точки.

Точки (OSM): amenity=research_institute|university|college, office=research,
building=university. Вес = затухание по расстоянию до БЛИЖАЙШЕЙ точки, поэтому
плотность объектов внутри кампуса на вес не влияет — только его наличие.
Считается оффлайн (scripts/compute_masks_overpass --only science), кэшируется в
data/processed/science_<slug>.csv.
"""

import numpy as np

# Больше, чем у distance_to_city (10 км): научная агломерация — это город с
# вузом плюс его пригороды, а не только сам кампус. Меньше, чем у
# distance_to_center (30 км): сигнал должен различать наукоград и соседний
# райцентр, а не размазываться на полрегиона.
SIGMA_KM = 15.0


def compute_science_mask(grid, col="science_access"):
    if col not in grid.columns:
        return np.zeros(len(grid))
    return grid[col].fillna(0).to_numpy()


