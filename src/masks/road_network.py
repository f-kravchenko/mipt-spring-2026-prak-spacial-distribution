"""
Маска дорожной сети с типизацией (§5.3).

Близость к дорогам разного класса как прокси транспортной доступности:
федеральные (motorway/trunk) тянут активность дальше, местные (secondary) —
ближе. Вес = нормированная сумма затуханий по расстоянию до ближайшей дороги
каждого класса. Веса считаются в PostGIS прямо по таблице `road` (геометрия
с GiST-индексом), поэтому модуль содержит только контракт и тиры — само
вычисление в etl.ingest.load_road_network_mask.
"""

import numpy as np

# tier -> (regex по тегу highway, sigma в км, вес класса)
ROAD_TIERS = {
    "federal":  ("motorway|trunk", 15.0, 0.5),
    "regional": ("primary",         8.0, 0.3),
    "local":    ("secondary",       4.0, 0.2),
}


def compute_road_network_mask(grid, col="road_access"):
    """Для совместимости с python-пайплайном: читает предрасчитанный столбец
    (0..1). В ETL веса считаются в БД, поэтому здесь — мягкий фолбэк."""
    if col not in grid.columns:
        return np.zeros(len(grid))
    return grid[col].fillna(0).to_numpy()


